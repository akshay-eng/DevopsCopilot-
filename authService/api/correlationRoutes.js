function buildFingerprint(cluster) {
  const parts = [
    ...(cluster.alert_names || []).sort(),
    ...(cluster.pods || []).sort(),
    ...(cluster.namespaces || []).sort(),
  ];
  return crypto.createHash('sha256').update(parts.join('|')).digest('hex').slice(0, 16);
}

function decryptConfig(integration) {
  const key = process.env.INTEGRATION_ENCRYPTION_KEY;
  const enc = integration.encryptedConfig;
  if (!key || !enc || !enc.encryptedData) return null;
  try {
    const decipher = crypto.createDecipheriv(
      'aes-256-gcm',
      Buffer.from(key, 'hex'),
      Buffer.from(enc.iv, 'hex')
    );
    decipher.setAuthTag(Buffer.from(enc.authTag, 'hex'));
    let dec = decipher.update(enc.encryptedData, 'hex', 'utf8');
    dec += decipher.final('utf8');
    return JSON.parse(dec);
  } catch (e) {
    console.error('Failed to decrypt integration config:', e.message);
    return null;
  }
}

async function createSnowIncident(userId, incident) {
  try {
    const integration = await Integration.findOne({ userId, type: 'snow', enabled: true });
    if (!integration) {
      console.log('[SNOW] No enabled ServiceNow integration found for user:', userId);
      return null;
    }

    const config = decryptConfig(integration);
    if (!config) {
      console.error('[SNOW] Failed to decrypt ServiceNow config for user:', userId);
      return null;
    }
    console.log('[SNOW] Creating incident for root cause:', incident.rootCause?.pod, 'instance:', config.instance_url);

    const auth = Buffer.from(`${config.username}:${config.password}`).toString('base64');
    const sevMap = { critical: 1, high: 2, warning: 3, medium: 3, low: 4, info: 5 };
    const topSeverity = Object.keys(incident.severities || {}).reduce((best, s) =>
      (sevMap[s] || 5) < (sevMap[best] || 5) ? s : best, 'info');

    // Prefer the written narrative — the structured dump below is already
    // appended to it — and fall back to the dump only if none was produced.
    const description = incident.description || [
      `Root Cause: ${incident.rootCause?.pod || 'Unknown'} (ns/${incident.rootCause?.namespace || 'unknown'})`,
      `Score: ${incident.rootCause?.score?.toFixed(3) || 'N/A'}`,
      `Alerts: ${incident.alertCount} across ${incident.pods?.length || 0} pods`,
      `Alert Names: ${(incident.alertNames || []).join(', ')}`,
      `Namespaces: ${(incident.namespaces || []).join(', ')}`,
      `Pods: ${(incident.pods || []).join(', ')}`,
      `Time Range: ${incident.timeRange?.start || ''} to ${incident.timeRange?.end || ''}`,
      '',
      'Evidence:',
      ...(incident.evidence || []).map(e => `  - ${e}`),
      '',
      'Causal Chain:',
      ...(incident.causalChain || []).map(c => `  ${c.role}: ${c.pod} (score: ${c.score})`),
      '',
      `Anomaly Summary: ${incident.rootCause?.anomalySummary || 'N/A'}`,
      `Occurrences: ${incident.occurrences || 1}`,
      '',
      `Generated by DevOps Copilot Correlation Engine`,
    ].join('\n');

    const body = {
      short_description: (incident.title
        || `[Correlated] ${incident.rootCause?.pod || 'Unknown'}: ${(incident.alertNames || []).slice(0, 3).join(', ')}`).slice(0, 160),
      description,
      urgency: sevMap[topSeverity] || 3,
      impact: sevMap[topSeverity] || 3,
      category: 'Software',
      subcategory: 'Application',
      assignment_group: config.assignment_group || '',
      caller_id: config.username,
    };

    const resp = await axios.post(
      `${config.instance_url}/api/now/table/incident`,
      body,
      {
        headers: { Authorization: `Basic ${auth}`, 'Content-Type': 'application/json' },
        timeout: 15000,
      }
    );

    const result = resp.data?.result;
    if (result) {
      console.log('[SNOW] Incident created:', result.number, 'sys_id:', result.sys_id);
      return {
        number: result.number,           // INC0012345
        sysId: result.sys_id,
        url: `${config.instance_url}/nav_to.do?uri=incident.do?sys_id=${result.sys_id}`,
        state: 'new',
        createdAt: new Date(),
      };
    }
    console.warn('[SNOW] No result in ServiceNow response');
    return null;
  } catch (err) {
    console.error('ServiceNow incident creation failed:', err.message);
    return null;
  }
}

async function storeCorrelationResults(userId, correlationData, clusterId, cronJobId) {
  const results = [];

  // A group of one is not a correlation.
  //
  // Correlation exists to say "these N separate alerts are one problem". When a
  // cluster holds a single condition there is nothing to correlate, and raising
  // a "[Correlated] ..." incident for it both misrepresents the finding and
  // floods ServiceNow with one ticket per stray alert. Those alerts are still
  // reported — through the normal alert path — they just do not get dressed up
  // as a correlation here.
  const MIN_CONDITIONS = Number(process.env.CORRELATION_MIN_CONDITIONS || 2);
  const groups = (correlationData.clusters || []).filter((c) => {
    const conditions = c.condition_count ?? c.alert_count ?? 0;
    const distinctAlertNames = (c.alert_names || []).length;
    // Either several distinct conditions, or one condition that is clearly
    // recurring across multiple pods — both are genuinely "more than one thing".
    const correlated = conditions >= MIN_CONDITIONS || distinctAlertNames >= MIN_CONDITIONS;
    if (!correlated) {
      console.log(`[CORRELATION] skipping single-condition group (${(c.alert_names || []).join(',')}) — nothing to correlate`);
    }
    return correlated;
  });

  for (const cluster of groups) {
    const fingerprint = buildFingerprint(cluster);
    const rca = cluster.root_cause_analysis || {};

    // Check for existing active incident with same fingerprint
    const existing = await CorrelatedIncident.findOne({
      userId, fingerprint, status: { $in: ['active', 'acknowledged'] },
    });

    if (existing) {
      // Increment occurrence counter
      existing.occurrences += 1;
      existing.lastSeenAt = new Date();
      existing.alertCount = cluster.alert_count || existing.alertCount;
      existing.conditionCount = cluster.condition_count || existing.conditionCount;
      existing.occurrenceCount = cluster.occurrence_count || existing.occurrenceCount;
      if (cluster.nodes?.length) existing.nodes = cluster.nodes;
      if (cluster.workloads?.length) existing.workloads = cluster.workloads;
      if (cluster.families?.length) existing.families = cluster.families;
      existing.statuses = cluster.statuses || existing.statuses;
      existing.timeRange = {
        start: cluster.time_range?.start,
        end: cluster.time_range?.end,
        durationSeconds: cluster.time_range?.duration_seconds,
      };
      existing.anomalyDetails = cluster.anomaly_details || existing.anomalyDetails;
      existing.executionTimeMs = correlationData.execution_time_ms;
      if (rca.topology) existing.topology = rca.topology;
      if (rca.evidence) existing.evidence = rca.evidence;
      if (cronJobId) existing.cronJobId = cronJobId;

      // An incident stored before narratives existed still has none; fill it in
      // once rather than leaving older incidents permanently undescribed.
      try {
        await ensureNarrative(existing);
      } catch (e) {
        console.warn('[CORRELATION] narrative backfill failed:', e.message);
      }

      // Auto-create SNOW incident if not already created
      if (!existing.snowIncident?.number) {
        const snowResult = await createSnowIncident(userId, existing);
        if (snowResult) {
          existing.snowIncident = snowResult;
          console.log(`[SNOW] Auto-created ticket ${snowResult.number} for existing incident ${existing.fingerprint}`);
        }
      }

      await existing.save();
      results.push(existing);
    } else {
      // Create new correlated incident
      const doc = new CorrelatedIncident({
        userId,
        clusterId: clusterId || '',
        fingerprint,
        occurrences: 1,
        firstSeenAt: new Date(),
        lastSeenAt: new Date(),
        rootCause: {
          pod: rca.root_cause?.pod,
          namespace: rca.root_cause?.namespace,
          score: rca.root_cause?.score,
          anomalySummary: rca.root_cause?.anomaly_summary,
          anomalousMetrics: rca.root_cause?.anomalous_metrics || [],
        },
        alertCount: cluster.alert_count,
        conditionCount: cluster.condition_count || cluster.alert_count,
        occurrenceCount: cluster.occurrence_count || cluster.alert_count,
        alertNames: cluster.alert_names || [],
        pods: cluster.pods || [],
        nodes: cluster.nodes || [],
        workloads: cluster.workloads || [],
        families: cluster.families || [],
        namespaces: cluster.namespaces || [],
        severities: cluster.severities || {},
        statuses: cluster.statuses || {},
        causalChain: rca.causal_chain || [],
        evidence: rca.evidence || [],
        topology: rca.topology || { nodes: [], edges: [] },
        downstreamImpact: rca.downstream_impact || [],
        anomalyDetails: cluster.anomaly_details || {},
        timeRange: {
          start: cluster.time_range?.start,
          end: cluster.time_range?.end,
          durationSeconds: cluster.time_range?.duration_seconds,
        },
        executionTimeMs: correlationData.execution_time_ms,
        cronJobId: cronJobId || null,
      });

      // Write the narrative BEFORE the ticket, so ServiceNow receives the
      // readable description rather than a field dump.
      try {
        await ensureNarrative(doc);
      } catch (e) {
        console.warn('[CORRELATION] narrative failed:', e.message);
      }

      await doc.save();

      // Try to create ServiceNow incident
      const snowResult = await createSnowIncident(userId, doc);
      if (snowResult) {
        doc.snowIncident = snowResult;
        await doc.save();
      }

      results.push(doc);
    }
  }

  return results;
}


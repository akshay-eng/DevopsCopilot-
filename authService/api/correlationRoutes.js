// POST /api/correlation/cron — Start a recurring correlation job
router.post('/cron', protect, async (req, res) => {
  try {
    const { intervalMinutes = 15, clusterId, hours = 48 } = req.body;
    const userId = req.user._id.toString();
    const token = req.headers.authorization?.replace('Bearer ', '');
    const cronKey = `${userId}:${clusterId || 'all'}`;

    // Clear existing job for this user/cluster
    if (cronJobs.has(cronKey)) {
      clearInterval(cronJobs.get(cronKey).intervalId);
      cronJobs.delete(cronKey);
    }

    const intervalMs = Math.max(5, parseInt(intervalMinutes)) * 60 * 1000;
    const cronJobId = crypto.randomUUID();

    const runJob = async () => {
      try {
        console.log(`[Cron ${cronJobId}] Running correlation for user=${userId} cluster=${clusterId || 'all'}`);
        const response = await axios.post(`${CORRELATION_URL}/api/correlate`, {
          userId, clusterId, token, hours: parseInt(hours),
        }, { timeout: 300000 });

        if (response.data.success && response.data.clusters?.length > 0) {
          await storeCorrelationResults(userId, response.data, clusterId, cronJobId);
          console.log(`[Cron ${cronJobId}] Stored ${response.data.clusters.length} clusters`);
        }
      } catch (err) {
        console.error(`[Cron ${cronJobId}] Error:`, err.message);
      }
    };

    // Run immediately, then on interval
    runJob();
    const intervalId = setInterval(runJob, intervalMs);

    cronJobs.set(cronKey, {
      intervalId,
      cronJobId,
      userId,
      clusterId: clusterId || 'all',
      intervalMinutes: parseInt(intervalMinutes),
      hours: parseInt(hours),
      startedAt: new Date(),
    });

    res.json({
      success: true,
      cronJobId,
      intervalMinutes: parseInt(intervalMinutes),
      message: `Correlation will run every ${intervalMinutes} minutes`,
    });
  } catch (error) {
    res.status(500).json({ success: false, error: error.message });
  }
});

// DELETE /api/correlation/cron — Stop a recurring correlation job
router.delete('/cron', protect, async (req, res) => {
  try {
    const userId = req.user._id.toString();
    const { clusterId } = req.query;
    const cronKey = `${userId}:${clusterId || 'all'}`;

    if (cronJobs.has(cronKey)) {
      clearInterval(cronJobs.get(cronKey).intervalId);
      cronJobs.delete(cronKey);
      return res.json({ success: true, message: 'Cron job stopped' });
    }

    res.json({ success: true, message: 'No active cron job found' });
  } catch (error) {
    res.status(500).json({ success: false, error: error.message });
  }
});

// GET /api/correlation/cron — Get active cron job status
router.get('/cron', protect, async (req, res) => {
  try {
    const userId = req.user._id.toString();
    const jobs = [];
    for (const [key, job] of cronJobs.entries()) {
      if (job.userId === userId) {
        jobs.push({
          cronJobId: job.cronJobId,
          clusterId: job.clusterId,
          intervalMinutes: job.intervalMinutes,
          hours: job.hours,
          startedAt: job.startedAt,
        });
      }
    }
    res.json({ success: true, jobs });
  } catch (error) {
    res.status(500).json({ success: false, error: error.message });
  }
});


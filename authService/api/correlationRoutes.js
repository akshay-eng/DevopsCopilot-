// GET /api/correlation/incidents/by-alert — Find correlated incidents matching an alert name or pod
router.get('/incidents/by-alert', protect, async (req, res) => {
  try {
    const userId = req.user._id.toString();
    const { alertname, pod, clusterId } = req.query;
    if (!alertname && !pod) return res.status(400).json({ success: false, error: 'alertname or pod required' });

    const query = { userId };
    const orConds = [];
    if (alertname) orConds.push({ alertNames: alertname });
    if (pod) orConds.push({ pods: pod });
    if (orConds.length) query.$or = orConds;
    if (clusterId) query.clusterId = clusterId;

    const incidents = await CorrelatedIncident.find(query)
      .sort({ lastSeenAt: -1 })
      .limit(5)
      .lean();

    res.json({ success: true, incidents });
  } catch (error) {
    console.error('Get incidents by-alert error:', error.message);
    res.status(500).json({ success: false, error: error.message });
  }
});


// POST /api/correlation/analyze — Run full correlation
router.post('/analyze', protect, async (req, res) => {
  try {
    const { clusterId, hours = 48 } = req.body;
    const userId = req.user._id.toString();
    const token = req.headers.authorization?.replace('Bearer ', '');

    const response = await axios.post(`${CORRELATION_URL}/api/correlate`, {
      userId, clusterId, token, hours: parseInt(hours),
    }, { timeout: 300000 });

    res.json(response.data);
  } catch (error) {
    console.error('Correlation proxy error:', error.message);
    if (error.response) return res.status(error.response.status).json(error.response.data);
    res.status(503).json({ success: false, error: 'Correlation engine unavailable. Ensure it is running on port 5005.' });
  }
});

// POST /api/correlation/analyze-and-store — Run correlation + store results
router.post('/analyze-and-store', protect, async (req, res) => {
  try {
    const { clusterId, hours = 48 } = req.body;
    const userId = req.user._id.toString();
    const token = req.headers.authorization?.replace('Bearer ', '');

    const response = await axios.post(`${CORRELATION_URL}/api/correlate`, {
      userId, clusterId, token, hours: parseInt(hours),
    }, { timeout: 300000 });

    const data = response.data;
    if (data.success && data.clusters?.length > 0) {
      const stored = await storeCorrelationResults(userId, data, clusterId);
      data.storedIncidents = stored.map(s => ({
        _id: s._id, fingerprint: s.fingerprint, occurrences: s.occurrences,
        snowIncident: s.snowIncident || null,
      }));
    }

    res.json(data);
  } catch (error) {
    console.error('Correlation analyze-and-store error:', error.message);
    if (error.response) return res.status(error.response.status).json(error.response.data);
    res.status(503).json({ success: false, error: 'Correlation engine unavailable.' });
  }
});

